/** Canonical lookup key: lowercase, single-spaced, no surrounding punctuation. */
export function dictionaryKey(name: string): string {
  return name.toLowerCase().replace(/\s+/g, " ").replace(/^[\s.,;]+|[\s.,;]+$/g, "");
}

export function lookupDictionary(name: string): string | null {
  return DICTIONARY[dictionaryKey(name)] ?? null;
}
